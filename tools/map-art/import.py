# Brings hand-edited map art into the addon. For each art-edits/edited/<uiMapID> <name>.png
# (an edited copy of export.py's source), the 256-px tiles that differ from the client's
# are written to OpenMap/Media/Textures/MapArt/<uiMapID>_<tile>.tga and listed in
# OpenMap/Data/ArtEdits.lua; Stitch.lua draws those tiles instead of the client's.
# Only changed tiles ship, so cleaning a label costs one or two tiles.
#
# usage: python -P tools/map-art/import.py <db2 dir> <texture cache>
import os, re, sys
import numpy as np
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..", "..")
sys.path.insert(0, os.path.join(root, "tools"))
import clients   # the client the tools build for (OPENMAP_CLIENT)
# (WoW Forever's in art-edits/ itself, another client's in art-edits/<client>/)
edits_root = os.path.join(root, "art-edits", *([] if clients.NAME == "forever" else [clients.NAME]))
src_dir, edit_dir = os.path.join(edits_root, "source"), os.path.join(edits_root, "edited")
tex = os.path.join(clients.TEX, "MapArt")
os.makedirs(tex, exist_ok=True)
for f in os.listdir(tex):
    if f.endswith(".tga"): os.remove(os.path.join(tex, f))
TILE = 256                                # the art's tiles: 256 px (1002 x 668 -> 4 x 3, 3840 x 2560 -> 15 x 10)

edits = {}
for f in sorted(os.listdir(edit_dir)) if os.path.isdir(edit_dir) else []:
    m = re.match(r"(\d+) .*\.png$", f)
    if not m: continue
    mid = int(m.group(1))
    srcp = os.path.join(src_dir, f)
    if not os.path.exists(srcp):
        print("no source for", f, "(run export.py)"); continue
    a = np.asarray(Image.open(os.path.join(edit_dir, f)).convert("RGB")).astype(np.int16)
    b = np.asarray(Image.open(srcp).convert("RGB")).astype(np.int16)
    if a.shape != b.shape:
        print("size changed:", f, a.shape, "vs", b.shape, "- keep the export's size"); continue
    changed = []
    h, w = a.shape[:2]
    COLS = (w + TILE - 1) // TILE
    for row in range((h + TILE - 1) // TILE):
        for col in range(COLS):
            ys, xs = slice(row * TILE, min(h, (row + 1) * TILE)), slice(col * TILE, min(w, (col + 1) * TILE))
            if np.abs(a[ys, xs] - b[ys, xs]).max() <= 2: continue
            tile = np.zeros((TILE, TILE, 3), np.uint8)
            part = a[ys, xs].astype(np.uint8)
            tile[:part.shape[0], :part.shape[1]] = part
            index = row * COLS + col + 1                  # (the art's file list is row-major, from 1)
            Image.fromarray(tile).save(os.path.join(tex, "%d_%d.tga" % (mid, index)))
            changed.append(index)
    if changed:
        edits[mid] = changed
        print(f, "tiles", changed)

with open(os.path.join(clients.DATA, "ArtEdits.lua"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write("-- Hand-cleaned map art (sea lettering removed ...): [uiMapID] = { tile, ... }, the tiles (row-major,\n")
    fh.write("-- from 1) drawn from Media/Textures/MapArt/<uiMapID>_<tile> instead of the client's.\n")
    fh.write("-- Generated by tools/map-art/import.py from art-edits/edited/; regenerate rather than edit.\n\n")
    fh.write("local _, ns = ...\n\nns.MapArtEdits = {\n")
    for mid, tiles in sorted(edits.items()):
        fh.write("\t[%d] = { %s },\n" % (mid, ", ".join(map(str, tiles))))
    fh.write("}\n")
print(len(edits), "maps edited")
