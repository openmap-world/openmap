# Builds OpenMap/Data/<client>/FlightData.lua from WoW Forever's flight tables (TaxiNodes, TaxiPath,
# TaxiPathNode as CSV from wago.tools, build 1.60.1.70245:
# https://wago.tools/db2/TaxiNodes/csv?build=1.60.1.70245). They hold the whole classic network
# (every node, path and cost of Classic Era 1.15.9's, with Stormwind's flight master moved a few
# yards and two dozen paths redrawn) and Forever's own flight masters. The boat and zeppelin
# paths are tools/map-data/build.py's. Another client's (OPENMAP_CLIENT, tools/clients.py) from its own
# build's tables: only the flight masters on its stitched world (Data/<client>/World.lua).
# usage: python -P tools/map-flights/flights.py <csv dir> <out lua>
import csv, sys, os, math
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import clients, uimap
WORLD = uimap.read_world(os.path.join(clients.DATA, "World.lua"))
FOREVER = clients.NAME == "forever"
d, out = sys.argv[1], sys.argv[2]
read = lambda n: list(csv.DictReader(open(os.path.join(d, n + ".csv"), encoding="utf-8")))
TOL = 20.0   # yards: waypoints kept within this of the real path

# Forever's Powderfuse Port flight masters have neither faction's map flag (as classic's unused
# nodes have): their faction is their mount's (MountCreatureID_0 is a node's Horde mount, _1 its
# Alliance one, as on every flagged node)
UNFLAGGED = {3274, 3275} if FOREVER else set()
# in the tables ahead of their zone: Mount Hyjal (its areas have no level yet in this build)
NOT_YET = {559, 3242} if FOREVER else set()
OLD = ("Transport", "Quest Path", "zzOLD")     # boats, scripted quest flights, retired nodes

nodes = {}
for r in read("TaxiNodes"):
    i = int(r["ID"])
    flags = int(r["Flags"]) & 3
    if i in UNFLAGGED: flags = (2 if r["MountCreatureID_0"] != "0" else 0) | (1 if r["MountCreatureID_1"] != "0" else 0)
    if flags == 0 or i in NOT_YET or r["Name_lang"].startswith(OLD): continue
    if not uimap.on_world(WORLD, int(r["ContinentID"]), float(r["Pos_0"]), float(r["Pos_1"]), 0.05): continue
    nodes[i] = (r["Name_lang"], int(r["ContinentID"]), float(r["Pos_0"]), float(r["Pos_1"]), flags)

pts = {}
for r in read("TaxiPathNode"):
    pts.setdefault(int(r["PathID"]), []).append((int(r["NodeIndex"]), float(r["Loc_0"]), float(r["Loc_1"]), int(r["ContinentID"])))

def rdp(p):
    if len(p) < 3: return p
    (x1, y1), (x2, y2) = p[0], p[-1]
    dx, dy = x2 - x1, y2 - y1; L = math.hypot(dx, dy) or 1e-9
    i, dm = 0, -1
    for k in range(1, len(p) - 1):
        dd = abs(dy * p[k][0] - dx * p[k][1] + x2 * y1 - y2 * x1) / L
        if dd > dm: i, dm = k, dd
    if dm <= TOL: return [p[0], p[-1]]
    return rdp(p[:i + 1])[:-1] + rdp(p[i:])

paths = []
for r in read("TaxiPath"):
    a, b, pid = int(r["FromTaxiNode"]), int(r["ToTaxiNode"]), int(r["ID"])
    if a not in nodes or b not in nodes or pid not in pts: continue
    p = sorted(pts[pid])
    if len({q[3] for q in p}) > 1: continue          # crosses continents: not a flight
    xy = [(q[1], q[2]) for q in p]
    length = sum(math.hypot(xy[k + 1][0] - xy[k][0], xy[k + 1][1] - xy[k][1]) for k in range(len(xy) - 1))
    paths.append((a, b, round(length), rdp(xy), int(r["Cost"])))

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("-- The flight network (%s tables, build %s): nodes and the paths flights take.\n" % ("WoW Forever's" if FOREVER else "the game's", clients.BUILD))
    f.write("-- Generated by tools/map-flights/flights.py; regenerate rather than edit.\n")
    f.write("--   nodes[id] = { name, continentID, worldX, worldY, factions (1 Alliance, 2 Horde) }\n")
    f.write("--   paths[i]  = { from, to, length (yards), cost (copper), { x1, y1, x2, y2, ... } }\n\n")
    f.write("local _, ns = ...\n\nns.MapFlights = {\n\tnodes = {\n")
    for i in sorted(nodes):
        n = nodes[i]
        f.write('\t\t[%d] = { %s, %d, %.1f, %.1f, %d },\n' % (i, '"' + n[0].replace('"', '\\"') + '"', n[1], n[2], n[3], n[4]))
    f.write("\t},\n\tpaths = {\n")
    for a, b, L, xy, cost in paths:
        f.write("\t\t{ %d, %d, %d, %d, { %s } },\n" % (a, b, L, cost, ", ".join("%.0f, %.0f" % q for q in xy)))
    f.write("\t},\n}\n")
print(len(nodes), "nodes", len(paths), "paths", sum(len(p[3]) for p in paths), "points")
