# Builds OpenMap/Data/FlightData.lua from the flight tables (TaxiNodes, TaxiPath,
# TaxiPathNode as CSV from wago.tools). It reads the Classic Era build's
# (https://wago.tools/db2/TaxiNodes/csv?build=1.15.9.70003): its flight network is the
# classic one, and its node names and costs are complete. WoW Forever's own tables carry
# the boat and zeppelin paths (tools/map-data/build.py).
# usage: python -P tools/map-flights/flights.py <csv dir> <out lua>
import csv, sys, os, math
d, out = sys.argv[1], sys.argv[2]
read = lambda n: list(csv.DictReader(open(os.path.join(d, n + ".csv"), encoding="utf-8")))
TOL = 20.0   # yards: waypoints kept within this of the real path

nodes = {}
for r in read("TaxiNodes"):
    flags = int(r["Flags"]) & 3
    if flags == 0 or r["Name_lang"].startswith("Transport"): continue
    nodes[int(r["ID"])] = (r["Name_lang"], int(r["ContinentID"]), float(r["Pos_0"]), float(r["Pos_1"]), flags)

pts = {}
for r in read("TaxiPathNode"):
    pts.setdefault(int(r["PathID"]), []).append((int(r["NodeIndex"]), float(r["Loc_0"]), float(r["Loc_1"]), int(r["ContinentID"])))

def rdp(p):
    if len(p) < 3: return p
    (x1, y1), (x2, y2) = p[0], p[-1]
    dx, dy = x2 - x1, y2 - y1; L = math.hypot(dx, dy) or 1e-9
    i, dm = 0, -1
    for k in range(1, len(p) - 1):
        dd = abs(dy * p[k][0] - dx * p[k][1] + x2 * y1 - y2 * x1) / L
        if dd > dm: i, dm = k, dd
    if dm <= TOL: return [p[0], p[-1]]
    return rdp(p[:i + 1])[:-1] + rdp(p[i:])

paths = []
for r in read("TaxiPath"):
    a, b, pid = int(r["FromTaxiNode"]), int(r["ToTaxiNode"]), int(r["ID"])
    if a not in nodes or b not in nodes or pid not in pts: continue
    p = sorted(pts[pid])
    if len({q[3] for q in p}) > 1: continue          # crosses continents: not a flight
    xy = [(q[1], q[2]) for q in p]
    length = sum(math.hypot(xy[k + 1][0] - xy[k][0], xy[k + 1][1] - xy[k][1]) for k in range(len(xy) - 1))
    paths.append((a, b, round(length), rdp(xy), int(r["Cost"])))

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("-- The flight network (Classic Era 1.15 tables): nodes and the paths flights take.\n")
    f.write("-- Generated by tools/map-flights/flights.py; regenerate rather than edit.\n")
    f.write("--   nodes[id] = { name, continentID, worldX, worldY, factions (1 Alliance, 2 Horde) }\n")
    f.write("--   paths[i]  = { from, to, length (yards), cost (copper), { x1, y1, x2, y2, ... } }\n\n")
    f.write("local _, ns = ...\n\nns.MapFlights = {\n\tnodes = {\n")
    for i in sorted(nodes):
        n = nodes[i]
        f.write('\t\t[%d] = { %s, %d, %.1f, %.1f, %d },\n' % (i, '"' + n[0].replace('"', '\\"') + '"', n[1], n[2], n[3], n[4]))
    f.write("\t},\n\tpaths = {\n")
    for a, b, L, xy, cost in paths:
        f.write("\t\t{ %d, %d, %d, %d, { %s } },\n" % (a, b, L, cost, ", ".join("%.0f, %.0f" % q for q in xy)))
    f.write("\t},\n}\n")
print(len(nodes), "nodes", len(paths), "paths", sum(len(p[3]) for p in paths), "points")
