# Bakes each zone's overall painted colour: OpenMap/Data/Tones.lua, [uiMapID] = { r, g, b },
# the median colour of the zone's own land in its overlay art. Close.lua tints the minimap
# overlay with it, so the minimap adds texture in the zone's own colours.
# usage: python -P tools/map-preview/tone.py <db2 dir> <texture cache>
import os, sys
import numpy as np

here = os.path.dirname(os.path.abspath(__file__))
db2, cache = sys.argv[1:3]
sys.argv = ["render.py", db2, cache, os.path.join(cache, "_preview")]
g = {"__name__": "tone", "__file__": os.path.join(here, "render.py")}
src = open(os.path.join(here, "render.py"), encoding="utf-8").read()
exec(compile(src[:src.index("views = sys.argv[4:]")], "render", "exec"), g)

rows = []
for m in g["zones"]:
    o = g["over"](m)
    if o is None or not o[..., 3].any(): continue
    land = g["own_land"](m) & (o[..., 3] > 0.9)
    if land.sum() < 1000: continue
    c = np.median(o[..., :3][land], axis=0)
    rows.append((m["id"], m["name"], c))
with open(os.path.join(g["WM"], "Tones.lua"), "w", encoding="utf-8", newline="\n") as f:
    f.write("-- Each zone's overall painted colour: [uiMapID] = { r, g, b }, the median of its land in its\n")
    f.write("-- overlay art. Generated by tools/map-preview/tone.py; regenerate rather than edit.\n\n")
    f.write("local _, ns = ...\n\nns.MapTones = {\n")
    for mid, name, c in sorted(rows):
        f.write("\t[%d] = { %.3f, %.3f, %.3f },  -- %s\n" % (mid, c[0], c[1], c[2], name))
    f.write("}\n")
print(len(rows), "zones")
