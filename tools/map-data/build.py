# Builds OpenMap's map data from the game's own tables (WoW Forever, build 1.60.1.70245):
#   OpenMap/Data/Reveal.lua   explored-area pieces per zone art   (WorldMapOverlay, WorldMapOverlayTile)
#   OpenMap/Data/Places.lua   instance entrances and levels, boat and zeppelin docks and routes
#                             (Map, LFGDungeons, ContentTuning, TaxiNodes, TaxiPath, TaxiPathNode)
# The tables are fetched as CSV from wago.tools into a cache folder.
# usage: python -P tools/map-data/build.py <cache dir> [build]
import csv, math, os, sys, time, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "..", "OpenMap", "Data")
cache = sys.argv[1]
BUILD = sys.argv[2] if len(sys.argv) > 2 else "1.60.1.70245"
os.makedirs(cache, exist_ok=True)

def table(name):
    p = os.path.join(cache, "%s-%s.csv" % (name, BUILD))
    if not os.path.exists(p) or os.path.getsize(p) < 100:
        req = urllib.request.Request("https://wago.tools/db2/%s/csv?build=%s" % (name, BUILD), headers={"User-Agent": "openmap-data/1"})
        open(p, "wb").write(urllib.request.urlopen(req, timeout=60).read())
        time.sleep(0.2)
    return list(csv.DictReader(open(p, encoding="utf-8")))

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

HEADER = "-- Generated by tools/map-data/build.py from the game's tables (build %s); regenerate rather than edit.\n\nlocal _, ns = ...\n\n" % BUILD

# ------------------------------------------------------------------ explored-area pieces
tiles = {}
for r in table("WorldMapOverlayTile"):
    if r["LayerIndex"] == "0":
        tiles.setdefault(r["WorldMapOverlayID"], []).append((int(r["RowIndex"]), int(r["ColIndex"]), r["FileDataID"]))
reveal = {}
for o in table("WorldMapOverlay"):
    t = tiles.get(o["ID"])
    if not t: continue
    key = "%s:%s:%s:%s" % (o["TextureWidth"], o["TextureHeight"], o["OffsetX"], o["OffsetY"])
    reveal.setdefault(int(o["UiMapArtID"]), {})[key] = ", ".join(f for _, _, f in sorted(t))
with open(os.path.join(DATA, "Reveal.lua"), "w", encoding="utf-8", newline="\n") as f:
    f.write("-- Explored-area pieces per zone art: [UiMapArtID] = { [\"w:h:x:y\"] = \"fileIDs, row-major\" }.\n")
    f.write(HEADER + "ns.MapReveal = {\n")
    for art in sorted(reveal):
        f.write("\t[%d] = {" % art + ", ".join("[%s] = %s" % (lua_str(k), lua_str(v)) for k, v in sorted(reveal[art].items())) + "},\n")
    f.write("}\n")
print("reveal:", len(reveal), "zone arts,", sum(len(v) for v in reveal.values()), "pieces")

# ------------------------------------------------------------------ instances
# Each dungeon's level, from the game's group finder: LFGDungeons points at a ContentTuning
# row whose level (MinLevelSquish) is the dungeon's. The group finder names some dungeons
# differently from the Map table, and lists Blackrock Spire / Dire Maul by wing: matched by
# name, a wing giving its lowest level. Ahn'Qiraj and Naxxramas aren't in it: no level shown.
tuning = {r["ID"]: int(r["MinLevelSquish"]) for r in table("ContentTuning")}
FINDER_NAMES = {"Stormwind Stockades": "Stormwind Stockade", "Zul'Farak": "Zul'Farrak", "Onyxia": "Onyxia's Lair",
                "Lower Blackrock Spire": "Blackrock Spire", "Upper Blackrock Spire": "Blackrock Spire",
                "Dire Maul - East": "Dire Maul", "Dire Maul - West": "Dire Maul", "Dire Maul - North": "Dire Maul"}
LEVELS = {}
for r in table("LFGDungeons"):
    lv = tuning.get(r["ContentTuningID"], 0)
    if r["TypeID"] != "0" or lv <= 0: continue
    name = FINDER_NAMES.get(r["Name_lang"], r["Name_lang"])
    LEVELS[name] = min(lv, LEVELS.get(name, lv))
inst = []
for r in table("Map"):
    kind = r["InstanceType"]
    if kind not in ("1", "2") or r["CorpseMapID"] not in ("0", "1"): continue
    x, y = float(r["Corpse_0"]), float(r["Corpse_1"])
    name = r["MapName_lang"]
    if (x == 0 and y == 0) or name.startswith("<") or "Test" in name: continue
    inst.append({"id": int(r["ID"]), "name": name, "raid": kind == "2", "cont": int(r["CorpseMapID"]), "x": x, "y": y})
groups = []           # entrances within 250 yards share a pin (Blackrock Mountain ...)
for i in sorted(inst, key=lambda i: i["id"]):
    g = next((g for g in groups if g["cont"] == i["cont"] and math.hypot(g["x"] - i["x"], g["y"] - i["y"]) < 250), None)
    if g: g["list"].append(i)
    else: groups.append({"cont": i["cont"], "x": i["x"], "y": i["y"], "list": [i]})

# ------------------------------------------------------------------ boats and zeppelins
nodes = {r["ID"]: r for r in table("TaxiNodes")}
pts = {}
for r in table("TaxiPathNode"):
    pts.setdefault(r["PathID"], []).append(r)
def thin(pts_, tol=15.0):
    """Douglas-Peucker, in yards"""
    if len(pts_) < 3: return pts_
    (x1, y1), (x2, y2) = pts_[0], pts_[-1]
    L = math.hypot(x2 - x1, y2 - y1) or 1e-9
    i, dm = 0, -1
    for k in range(1, len(pts_) - 1):
        dd = abs((y2 - y1) * pts_[k][0] - (x2 - x1) * pts_[k][1] + x2 * y1 - y2 * x1) / L
        if dd > dm: i, dm = k, dd
    if dm <= tol: return [pts_[0], pts_[-1]]
    return thin(pts_[:i + 1], tol)[:-1] + thin(pts_[i:], tol)

docks, sailings, sailed = [], [], set()
for p in table("TaxiPath"):
    n = nodes.get(p["FromTaxiNode"]) or nodes.get(p["ToTaxiNode"])
    if not n or not n["Name_lang"].startswith("Transport"): continue
    route = n["Name_lang"].split(",", 1)[1].strip()
    path = sorted(pts.get(p["ID"], []), key=lambda r: int(r["NodeIndex"]))
    stops = [r for r in path if r["Delay"] != "0"]
    zeppelin = "Zepplin" in route or "Orgrimmar" in route
    uniq = []
    for s in stops:
        c, x, y = int(s["ContinentID"]), float(s["Loc_0"]), float(s["Loc_1"])
        if not any(u[0] == c and math.hypot(u[1] - x, u[2] - y) < 60 for u in uniq): uniq.append((c, x, y))
    for k, (c, x, y) in enumerate(uniq):
        to = uniq[(k + 1) % len(uniq)] if len(uniq) > 1 else None
        docks.append({"kind": "zeppelin" if zeppelin else "boat", "route": route, "cont": c, "x": x, "y": y, "to": to})
    # the way the vessel actually sails, from its first stop to the next (one direction per
    # crossing), split where it passes from one continent's map to the other's
    ix = [path.index(s) for s in stops]
    i0 = ix[0] if ix else None
    i1 = next((j for j, s in zip(ix[1:], stops[1:]) if (int(s["ContinentID"]), round(float(s["Loc_0"]) / 60), round(float(s["Loc_1"]) / 60))
               != (int(stops[0]["ContinentID"]), round(float(stops[0]["Loc_0"]) / 60), round(float(stops[0]["Loc_1"]) / 60))), None)
    if i0 is None or i1 is None: continue
    ends = tuple(sorted(((uniq[0]), (uniq[1] if len(uniq) > 1 else uniq[0]))))
    key = tuple((c, round(x / 60), round(y / 60)) for c, x, y in ends)
    if key in sailed: continue
    sailed.add(key)
    segs, seg, last = [], [], None
    for r in path[min(i0, i1):max(i0, i1) + 1]:
        c = int(r["ContinentID"])
        x, y = float(r["Loc_0"]), float(r["Loc_1"])
        jump = seg and math.hypot(x - seg[-1][0], y - seg[-1][1]) > 2000      # the vessel is moved across the map
        if last is not None and (c != last or jump):
            if len(seg) > 1: segs.append((last, thin(seg)))
            seg = []
        seg.append((x, y)); last = c
    if len(seg) > 1: segs.append((last, thin(seg)))
    if segs: sailings.append(("zeppelin" if zeppelin else "boat", route, segs))

with open(os.path.join(DATA, "Places.lua"), "w", encoding="utf-8", newline="\n") as f:
    f.write("-- Places on the map, in world yards per continent (0 Eastern Kingdoms, 1 Kalimdor).\n")
    f.write("--   instances[i] = { continent, x, y, { { mapID, name, raid, level }, ... } }\n")
    f.write("--     (the entrance: where a ghost returns; entrances close together share one)\n")
    f.write("--   transports[i] = { \"boat\" | \"zeppelin\", route, continent, x, y, toContinent, toX, toY }\n")
    f.write("--   sailings[i] = { kind, route, { { continent, { x1, y1, x2, y2, ... } }, ... } }: the way it sails,\n")
    f.write("--     dock to dock, in pieces per continent map (between pieces it's crossing the open sea)\n")
    f.write(HEADER + "ns.MapPlaces = {\n\tinstances = {\n")
    for g in groups:
        items = ", ".join("{ %d, %s, %s, %s }" % (i["id"], lua_str(i["name"]), "true" if i["raid"] else "false",
            LEVELS.get(i["name"], "nil")) for i in g["list"])
        f.write("\t\t{ %d, %.1f, %.1f, { %s } },\n" % (g["cont"], g["x"], g["y"], items))
    f.write("\t},\n\ttransports = {\n")
    for d in docks:
        to = d["to"]
        f.write("\t\t{ %s, %s, %d, %.1f, %.1f, %s },\n" % (lua_str(d["kind"]), lua_str(d["route"]), d["cont"], d["x"], d["y"],
            ("%d, %.1f, %.1f" % to) if to else "nil, nil, nil"))
    f.write("\t},\n\tsailings = {\n")
    for kind, route, segs in sailings:
        f.write("\t\t{ %s, %s, { %s } },\n" % (lua_str(kind), lua_str(route), ", ".join(
            "{ %d, { %s } }" % (c, ", ".join("%.0f, %.0f" % q for q in pts_)) for c, pts_ in segs)))
    f.write("\t},\n}\n")
print("sailings:", len(sailings), [(k, r, len(sg)) for k, r, sg in sailings])
print("places:", len(groups), "instance entrances (", len(inst), "instances ),", len(docks), "docks")
