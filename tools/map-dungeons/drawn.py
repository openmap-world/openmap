# Builds the maps of WoW Forever's own dungeons, which the game has no map of: maps drawn by
# players who let OpenMap use them (art/drawn/dungeons, and its README), credited on the map.
#   OpenMap/Media/Textures/MapDungeonDrawn/<mapID>_<n>.tga   the picture in Blizzard's dungeon map
#                                       layout: 1002 x 668 in 4 x 3 tiles of 256 px (Map/Dungeons.lua's)
#   OpenMap/Data/DungeonDrawn.lua       per instance: its floor's tiles and who drew it
#
# usage: python -P tools/map-dungeons/drawn.py
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
ART = os.path.join(ROOT, "art", "drawn", "dungeons")
OUT = os.path.join(ROOT, "OpenMap", "Media", "Textures", "MapDungeonDrawn")
PIC_W, PIC_H = 1002, 668

# instance mapID (Data/Places.lua's) -> (the drawing, its name, who drew it)
DRAWN = {
    2959: ("city-of-dalaran.png", "City of Dalaran", "Santiago Reyes"),
    2998: ("excavation-site-wetlands.png", "Excavation Site: Wetlands", "Santiago Reyes"),
    2999: ("ruins-of-lordaeron.png", "Ruins of Lordaeron", "Santiago Reyes"),
    3065: ("hall-of-thanes.png", "The Hall of Thanes", "Santiago Reyes"),
}


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    os.makedirs(OUT, exist_ok=True)
    lines = [
        "-- WoW Forever's own dungeons' maps, which the game has none of: drawn by players who let OpenMap",
        "-- use them (art/drawn/dungeons), shown as Blizzard's dungeon maps are (Data/DungeonMaps.lua's layout)",
        "-- and credited on the map.",
        "--   [instance mapID] = { { tiles = { 12 textures, row-major }, credit = who drew it }, ... }",
        "-- Generated by tools/map-dungeons/drawn.py; regenerate rather than edit.",
        "",
        "local _, ns = ...",
        "",
        "local P = ns.Media.path .. \"Textures\\\\MapDungeonDrawn\\\\\"",
        "",
        "ns.MapDungeonDrawn = {",
    ]
    for mid, (art, name, credit) in sorted(DRAWN.items()):
        im = Image.open(os.path.join(ART, art)).convert("RGB").resize((PIC_W, PIC_H), Image.LANCZOS)
        page = Image.new("RGB", (1024, 768))
        page.paste(im, (0, 0))
        tiles = []
        for n in range(12):
            col, row = n % 4, n // 4
            f = "%d_%d" % (mid, n + 1)
            page.crop((col * 256, row * 256, col * 256 + 256, row * 256 + 256)).save(os.path.join(OUT, f + ".tga"))
            tiles.append("P .. " + lua_str(f))
        lines.append("\t[%d] = { -- %s" % (mid, name))
        lines.append("\t\t{ tiles = { %s }, credit = %s }," % (", ".join(tiles), lua_str(credit)))
        lines.append("\t},")
        print("%s: 12 tiles, by %s" % (name, credit))
    lines.append("}")
    with open(os.path.join(ROOT, "OpenMap", "Data", "DungeonDrawn.lua"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
