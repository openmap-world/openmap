# Builds OpenMap/Data/<client>/DungeonMaps.lua for a client whose own tables have its dungeon maps
# (retail): Blizzard's map of each instance in Places.lua (tools/map-data/build.py), a picture per floor,
# in the layout Map/Dungeons.lua draws (WoW Forever's has none: tools/map-dungeons/build.py makes its
# from another build's tables and its install).
#   - an instance's floors: the dungeon maps (UiMap type 4, or 6: a one-floor one's) the game places on its game map
#     (UiMapAssignment), in the order of their floors (UiMapGroupMember.FloorIndex), named as they are;
#   - a floor's wing: the journal instance whose bosses are on it (JournalEncounter.UiMapID), when the
#     instance has several (Dire Maul's quarters);
#   - only floors in the classic layout (1002 x 668 in 4 x 3 tiles of 256, all twelve there): the few
#     newer ones drawn larger (3840 x 2560) are left out and listed.
#
# usage: python -P tools/map-dungeons/tables.py <db2 dir>       (OPENMAP_CLIENT: the client, tools/clients.py)
import csv, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
import clients   # the client the tools build for (OPENMAP_CLIENT)
import uimap


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    db2 = sys.argv[1]
    w = uimap.World(db2)
    read = lambda n: list(csv.DictReader(open(os.path.join(db2, n + ".csv"), encoding="utf-8")))
    places = open(os.path.join(clients.DATA, "Places.lua"), encoding="utf-8").read()
    places = places[places.index("instances = {"):places.index("bosses = {")]
    instances = []                  # (mapID, name), in Places' order, a wing each
    for mid, name in re.findall(r'\{ (\d+), "((?:[^"\\]|\\.)*)", (?:true|false)', places):
        if (int(mid), name) not in instances: instances.append((int(mid), name))

    tiles_of = {}
    for r in read("UiMapArtTile"):
        if r["LayerIndex"] == "0":
            tiles_of.setdefault(int(r["UiMapArtID"]), {})[(int(r["RowIndex"]), int(r["ColIndex"]))] = int(r["FileDataID"])
    group = {int(r["UiMapID"]): r for r in read("UiMapGroupMember")}
    floors_of = {}
    for m, rows in w.assign.items():
        if w.uimap.get(m, {}).get("Type") not in ("4", "6"): continue   # (6: a one-floor instance's map)
        for a in rows:
            floors_of.setdefault(int(a["MapID"]), set()).add(m)
    jinst = {r["ID"]: r for r in read("JournalInstance")}
    wings_on, journals_of = {}, {}
    for r in read("JournalEncounter"):
        ji = jinst.get(r["JournalInstanceID"])
        if not ji: continue
        journals_of.setdefault(int(ji["MapID"]), set()).add(ji["Name_lang"])
        if r["UiMapID"] not in ("", "0"):
            wings_on.setdefault(int(r["UiMapID"]), set()).add(ji["Name_lang"])

    wings_listed = {}
    for mid, name in instances: wings_listed.setdefault(mid, []).append(name)
    out, left = {}, []
    for mid, name in instances:
        if mid in out: continue
        floors = []
        for u in sorted(floors_of.get(mid, ())):
            art = w.art(u)
            if not art: continue
            t = tiles_of.get(art[0], {})
            if art[1:3] != (1002, 668) or sorted(t) != [(r, c) for r in range(3) for c in range(4)]:
                left.append("  %s: UiMap %d (%s), %d x %d" % (name, u, w.uimap[u]["Name_lang"], art[1], art[2]))
                continue
            g = group.get(u)
            floors.append({"ui": u, "fids": [t[(r, c)] for r in range(3) for c in range(4)],
                           "name": g["Name_lang"] if g and g["Name_lang"] else None,
                           "order": (int(g["FloorIndex"]) if g else 99, u), "wings": wings_on.get(u, set())})
        floors.sort(key=lambda f: f["order"])
        split = len(wings_listed.get(mid, ())) > 1 or len(journals_of.get(mid, ())) > 1
        kept, seen = [], set()
        for f in floors:
            if tuple(f["fids"]) in seen: continue           # (the same picture twice: one floor)
            seen.add(tuple(f["fids"]))
            f["wing"] = next(iter(f["wings"])) if split and len(f["wings"]) == 1 else None
            kept.append(f)
        if kept:
            kept[0]["title"] = name if len(wings_listed[mid]) == 1 else w.uimap[kept[0]["ui"]]["Name_lang"]
            out[mid] = kept

    lines = [
        "-- Dungeon and raid maps: Blizzard's own map of each instance, a picture per floor (the classic",
        "-- world map layout: 4 x 3 tiles of 256 px, the picture ~1002 x 668 of its 1024 x 768).",
        "--   [instance mapID] = { { tiles = { 12 file IDs, row-major }, name = the floor's name (nil: the",
        "--     tables give none), wing = the wing whose bosses are on it (nil: one wing, or not said) }, ... }",
        "-- Generated by tools/map-dungeons/tables.py from the game's tables (build %s); regenerate rather than edit." % clients.BUILD,
        "",
        "local _, ns = ...",
        "",
        "ns.MapDungeonMaps = {",
    ]
    for key in sorted(out):
        floors = out[key]
        lines.append("\t[%d] = { -- %s" % (key, floors[0]["title"]))
        for f in floors:
            extra = ""
            if f["name"]: extra += ", name = " + lua_str(f["name"])
            if f["wing"]: extra += ", wing = " + lua_str(f["wing"])
            lines.append("\t\t{ tiles = { %s }%s }," % (", ".join(str(x) for x in f["fids"]), extra))
        lines.append("\t},")
    lines.append("}")
    path = os.path.join(clients.DATA, "DungeonMaps.lua")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote %s: %d instances, %d floors" % (os.path.relpath(path, clients.REPO), len(out), sum(len(v) for v in out.values())))
    missing = [name for mid, name in instances if mid not in out]
    if missing: print("instances without a floor in the classic layout:", ", ".join(sorted(set(missing))))
    if left: print("floors left out (not the classic layout):\n" + "\n".join(left))


if __name__ == "__main__":
    main()
